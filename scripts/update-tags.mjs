import { writeFile, rename } from 'node:fs/promises';
import { gunzipSync } from 'node:zlib';

const headers = { 'User-Agent': 'ArcanaDeckbuilder/0.1 (local deckbuilding app)', Accept: 'application/json' };
async function get(url) {
  const response = await fetch(url, { headers, signal: AbortSignal.timeout(60_000) });
  if (!response.ok) throw Error(`Scryfall returned ${response.status}`);
  return response;
}

const source = 'https://api.scryfall.com/bulk-data/oracle_tags';
const bulk = await (await get(source)).json();
const download = new URL(bulk.jsonl_download_uri);
if (download.protocol !== 'https:' || download.hostname !== 'data.scryfall.io') throw Error('Unexpected bulk download host.');
const bytes = Buffer.from(await (await get(download)).arrayBuffer());
const rows = gunzipSync(bytes).toString('utf8').trim().split('\n').map(JSON.parse);
const slugs = new Map(rows.map(t => [t.id, t.slug]));
const tags = rows.map(t => {
  const aliases = t.aliases ?? [];
  if (t.type !== 'oracle' || typeof t.id !== 'string' || !/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(t.slug) || !Array.isArray(aliases) || aliases.some(a => typeof a !== 'string')) throw Error('Unexpected tag schema.');
  const links = ids => (ids ?? []).map(id => {
    if (!slugs.has(id)) throw Error(`Missing relationship: ${id}`);
    return slugs.get(id);
  }).sort();
  return { uuid: t.id, id: t.slug, aliases, parents: links(t.parent_ids), children: links(t.child_ids) };
}).sort((a, b) => a.id.localeCompare(b.id, 'en'));
if (!tags.length || slugs.size !== tags.length || new Set(tags.map(t => t.id)).size !== tags.length || !Number.isFinite(Date.parse(bulk.updated_at))) throw Error('Invalid tag catalog.');
const catalog = { source, updated: bulk.updated_at, tags };
const file = new URL('../public/tag-catalog.js', import.meta.url);
const temporary = new URL('../public/tag-catalog.js.tmp', import.meta.url);
await writeFile(temporary, '// Generated by scripts/update-tags.mjs from Scryfall Oracle Tags. Do not edit.\nexport const TAG_CATALOG = ' + JSON.stringify(catalog, null, 0) + ';\n');
await rename(temporary, file);
console.log(`Updated ${tags.length} Oracle tags (${bulk.updated_at}).`);
